#!/usr/bin/env python3
"""Price Alerts for trader-alerts: rings when a price, a stop, the opening
bell or the square-off hits. NSE/BSE, IST. Standard library only.
It never places an order.

    python3 alerts.py clock                      # is the market open, and when next
    python3 alerts.py quote RELIANCE TCS
    python3 alerts.py add --from-plan             # the stop, the target and flat-by in one go
    python3 alerts.py add --symbol TCS --above 4050
    python3 alerts.py check                       # rings whatever hit, once each
    python3 alerts.py list

Alert types:

  above / below   the price crossed your level
  stop / target   the same, labelled from the plan so the message says which
  pct_move        the price moved this percent or more from the previous close
  time            a plain IST time of day
  opening_bell    NSE opened today (rings once per trading day)
  square_off      your broker's intraday square-off is near, so get flat

Each rings ONCE so you are not spammed. A pct_move rings at most once a day.

Knows NSE hours (09:15 to 15:30 IST) and the holiday calendar from
config/india_market.py, including the Muhurat session, and works out IST
itself with no timezone files. Quotes come through config/datasource.py, so
the provider is swappable, and the last price for each symbol is written to
trader/prices.json for sizing and the risk check.

The square_off alert has no US equivalent and it matters: your broker closes
open intraday positions itself, around 15:20, at whatever price is there.
Being closed by your broker is not an exit you chose.

Free delayed data is unofficial and can lag. Check anything that matters
against your broker. Day trading loses most people money.
"""

