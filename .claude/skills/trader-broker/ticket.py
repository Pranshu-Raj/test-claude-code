#!/usr/bin/env python3
"""Order Executor for trader-broker: shows the ticket, records your yes, and
never places anything by itself. Indian cash equity intraday. Standard
library only.

    python3 ticket.py show                       # every ticket, READY or not
    python3 ticket.py show --index 1 --json
    python3 ticket.py approve --index 1 --reply "yes"
    python3 ticket.py result --index 1 --status placed --broker-id 2510...
    python3 ticket.py flatten                    # the square-off ticket
    python3 ticket.py fill --index 1 --price 4026.50

An order is READY only when trader-risk recorded a PASS for THAT exact order
(same fingerprint) today, and you have not already acted on it. Then you type
yes for that one order, and Claude's own Allow once card asks again. Three
gates, none of them skippable.

THREE LEGS, NOT A BRACKET. Alpaca takes one bracket order carrying its own
stop and target. Kite withdrew Bracket Orders, so the same trade is three
separate orders: the entry, an SL-M stop and a LIMIT target. The stop and the
target go in only after the entry fills, and they are NOT linked to each
other: if the target fills, the stop is still live and must be cancelled, or
you are left short. Every ticket says so, because there is no US equivalent
of that footgun.

SQUARE-OFF. Your broker closes open intraday positions itself, around 15:20.
`flatten` builds the market SELL that gets you out first, on your terms.

Paper trading is the default. Keys live in environment variables, never in
the chat and never in a file here.
"""

