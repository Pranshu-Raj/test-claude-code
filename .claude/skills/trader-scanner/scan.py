def progress(a, msg):
    if not getattr(a, "json", False) and not getattr(a, "quiet", False):
        print(msg, file=sys.stderr)


def series_from_canonical(series):
    """A config.datasource series -> the plain lists the scans expect."""
    bars = series.get("bars") or []
    meta = dict(series.get("meta") or {})
    return {"t": [b["t"] for b in bars], "c": [b["c"] for b in bars],
            "o": [b["o"] for b in bars], "h": [b["h"] for b in bars],
            "l": [b["l"] for b in bars], "v": [b.get("v") or 0 for b in bars],
            "meta": meta}


def fetch_series(symbols, interval, pause, adapter=None, data_dir=None, a=None, days=None):
    """One request per symbol through the adapter. -> ({SYM: series}, {SYM: error}).

    The US version used Yahoo's spark endpoint in batches of 20, which only
    that one provider offers. Going one at a time through the adapter keeps
    every provider interchangeable, which is the point of the adapter.
    """
    data, failed = {}, {}
    try:
        ad = adapter if hasattr(adapter, "bars") else ds.get_adapter(
            adapter, **({"directory": data_dir} if (adapter or "") == "offline" else {}))
    except ds.DataError as e:
        return {}, dict((s, str(e)) for s in symbols)
    for k, sym in enumerate(symbols):
        if k and pause and getattr(ad, "name", "") != "offline":
            SLEEP(pause)
        try:
            data[sym] = series_from_canonical(ad.bars(sym, interval, days=days))
        except ds.DataError as e:
            failed[sym] = str(e)
        if a is not None and len(symbols) > 50 and (k + 1) % 100 == 0:
            progress(a, "  %d of %d symbols" % (k + 1, len(symbols)))
    return data, failed


def fetch_spark(symbols, rng, interval, pause, a=None):
    """Kept for the tests that drive the old batch path directly."""
    data, failed = {}, {}
    batches = [symbols[i:i + SPARK_MAX] for i in range(0, len(symbols), SPARK_MAX)]
    for k, batch in enumerate(batches):
        if k and pause:
            SLEEP(pause)
        wanted = {to_yahoo(s): s for s in batch}
        try:
            got = parse_spark(yahoo_get(spark_path(batch, rng, interval)), wanted)
        except (ScanError, ValueError) as e:
            for s in batch:
                failed[s] = str(e)
            continue
        for s in batch:
            if s in got:
                data[s] = got[s]
            else:
                failed[s] = "no data from Yahoo"
        if a is not None and len(batches) > 25 and (k + 1) % 50 == 0:
            progress(a, "  spark %d of %d requests" % (k + 1, len(batches)))
    return data, failed


def read_symbols(a, offline_syms=None):
    if a.symbols:
        syms = [s for s in re.split(r"[,\s]+", a.symbols.upper()) if s]
    elif a.watchlist:
        syms = symbols_from_file(a.watchlist)
    elif offline_syms is not None and not a.universe:
        syms = sorted(offline_syms)  # offline: every chart in the file, unless a list was given
    else:
        path = a.universe or DEFAULT_UNIVERSE
        if not os.path.exists(path):
            raise ScanError("no %s yet: run `scan.py universe` first, or pass --symbols" % path)
        syms = symbols_from_file(path)
    out = []
    for s in syms:
        if s not in out:
            out.append(s)
    if a.limit:
        out = out[:a.limit]
    if not out:
        raise ScanError("no symbols to scan")
    return out


def symbols_from_file(path):
    if not os.path.exists(path):
        raise ScanError("no file at %s" % path)
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    if text.lstrip().startswith(("{", "[")):
        try:
            doc = json.loads(text)
        except ValueError as e:
            raise ScanError("%s is not valid JSON: %s" % (path, e))
        items = doc.get("hits", []) if isinstance(doc, dict) else doc
        return [str(x.get("symbol") if isinstance(x, dict) else x).upper() for x in items if x]
    out = []
    for ln in text.splitlines():
        ln = ln.strip()
        if ln and not ln.startswith("#"):
            out.append(ln.split("|")[0].strip().upper())
    return out


def read_config(path):
    if not path or not os.path.exists(path):
        return {}
    try:
        with open(path, encoding="utf-8") as fh:
            cfg = json.load(fh)
    except ValueError as e:
        raise ScanError("%s is not valid JSON: %s" % (path, e))
    return cfg if isinstance(cfg, dict) else {}


def write_json(path, doc):
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, indent=2)
        fh.write("\n")


def money(x):
    """A price in rupees, Indian digit grouping."""
    return mkt.format_inr_price(x)


